import { api, bash, chapter, ex, p, section } from './helpers';

// 第 17 章：net 与 dgram
export const netChapter = chapter('net', 'net / dgram', 'TCP 与 UDP：Socket 编程的底层基石', [
  section('net-tcp', 'TCP 编程', [
    api(
      'net-tcp-server',
      'net.createServer：TCP 服务端',
      'net.createServer(connectionListener?)',
      '创建 TCP 服务器。每个新连接触发一次 connection 回调，参数 socket 是全双工流，既能读也能写。HTTP/SSH/数据库协议的底层全是它。',
      [
        p('options.allowHalfOpen', 'boolean', false, '允许半开连接：对端 end() 后本端仍可继续写，默认 false'),
        p('connectionListener', '(socket: Socket) => void', false, '连接回调，等价于 server.on("connection")'),
      ],
      [
        ex('TCP Echo 回显服务', [
          "import * as net from 'node:net';",
          '',
          'const server = net.createServer((socket: net.Socket) => {',
          "  console.log('客户端接入:', socket.remoteAddress + ':' + socket.remotePort);",
          '',
          '  socket.on("data", (chunk: Buffer) => {',
          '    socket.write("ECHO: " + chunk.toString().trim());',
          '  });',
          '',
          '  socket.on("close", () => console.log("连接断开"));',
          '});',
          '',
          'server.listen(4000, () => {',
          "  console.log('TCP 服务已监听 4000 端口');",
          '});',
        ].join('\n'), 'TCP 服务已监听 4000 端口\n客户端接入: 127.0.0.1:52314\n连接断开'),
        bash('用 nc 测试连接', [
          'echo hello | nc 127.0.0.1 4000',
        ].join('\n'), 'ECHO: hello'),
      ],
      [
        'socket 是 Duplex 双工流：data/end/write 全套流式 API 可用，大流量场景自动获得背压保护。',
        'server.on("error") 必须监听：EADDRINUSE（端口占用）等错误不监听会让进程直接崩溃。',
        'server.maxConnections 限制并发连接数；黑名单封禁用 net.BlockList（v15+）。',
        'HTTP 场景不需要 net：http 模块已封装协议解析，net 用于自定义协议（IM/游戏/代理）。',
      ],
    ),
    api(
      'net-tcp-client',
      'net.connect：TCP 客户端',
      'net.connect(port[, host][, listener])',
      '连接 TCP 服务器并返回 Socket。连接成功触发 connect 事件，之后即可双向读写；接口与 tls.connect 完全一致，加密场景只换模块。',
      [
        p('port', 'number', true, '目标端口'),
        p('host', 'string', false, '目标主机，默认 localhost'),
        p('options.timeout', 'number', false, '空闲超时毫秒数，超时触发 timeout 事件（不自动断开）'),
      ],
      [
        ex('连接 Echo 服务并收发数据', [
          "import * as net from 'node:net';",
          '',
          'const socket = net.connect({ port: 4000, host: "127.0.0.1" });',
          '',
          'socket.setEncoding("utf8");',
          'socket.on("connect", () => {',
          '  socket.write("ping");',
          '});',
          '',
          'socket.on("data", (chunk: string) => {',
          "  console.log('收到:', chunk.trim());",
          '  socket.end();',
          '});',
          '',
          'socket.on("error", (err: Error) => {',
          "  console.error('连接失败:', (err as NodeJS.ErrnoException).code);",
          '});',
        ].join('\n'), '收到: ECHO: ping'),
      ],
      [
        'socket.write 返回 false 表示内核缓冲已满，应停写并等待 drain 事件，这是 TCP 客户端的背压姿势。',
        'ECONNREFUSED（对端未监听）走 error 事件，不监听会导致 uncaughtException 崩溃。',
        'socket.end() 发送 FIN 表示"我写完了"；socket.destroy() 立即销毁，用于超时强杀。',
        '连接池、重连退避（指数退避 + 抖动）业务层要自己实现，Socket 不会自动重连。',
      ],
    ),
  ]),
  section('dgram-udp', 'UDP 编程', [
    api(
      'dgram-udp',
      'dgram：UDP 数据报',
      'dgram.createSocket(type[, callback])',
      'UDP 无连接、不保序、不保证送达，但开销比 TCP 小一个量级。适合 DNS、日志采集、游戏同步、广播与多播场景。',
      [
        p('type', '"udp4" | "udp6"', true, '协议栈版本'),
        p('callback', '(msg, rinfo) => void', false, 'message 事件的快捷监听'),
      ],
      [
        ex('UDP 收发两端', [
          "import * as dgram from 'node:dgram';",
          '',
          '// 服务端',
          'const server = dgram.createSocket("udp4");',
          '',
          'server.on("message", (msg: Buffer, rinfo: dgram.RemoteInfo) => {',
          "  console.log('服务端收到:', msg.toString(), 'from', rinfo.address + ':' + rinfo.port);",
          '  server.send("pong", rinfo.port, rinfo.address);',
          '});',
          '',
          'server.bind(5001, () => console.log("UDP 服务就绪"));',
          '',
          '// 客户端',
          'const client = dgram.createSocket("udp4");',
          'client.send("ping", 5001, "127.0.0.1", () => {',
          "  console.log('已发送 ping');",
          '});',
          '',
          'client.on("message", (msg: Buffer) => {',
          "  console.log('客户端收到回执:', msg.toString());",
          '  client.close();',
          '  server.close();',
          '});',
        ].join('\n'), 'UDP 服务就绪\n已发送 ping\n服务端收到: ping from 127.0.0.1:53122\n客户端收到回执: pong'),
      ],
      [
        'send 的回调里检查错误：UDP"发送成功"只代表数据写入了内核缓冲，不代表对端收到。',
        '业务必须自行处理丢包与乱序；要求可靠性就直接换 TCP，别在 UDP 上重造协议。',
        'msg 是 Buffer，rinfo 携带来源地址端口；广播先 setBroadcast(true)，多播用 addMembership。',
        '内网服务发现常用 UDP 广播实现，注意云环境多数安全组默认禁广播。',
      ],
    ),
  ]),
]);
