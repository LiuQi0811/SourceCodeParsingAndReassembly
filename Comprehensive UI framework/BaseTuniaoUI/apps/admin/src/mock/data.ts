/** 生成近 3 天的操作日志，时间递减 */
export const logSeed: LogItem[] = Array.from({ length: 26 }).map((_, index) => {
  const dayOffset = Math.floor(index / 9)
  const hour = 21 - (index % 9) * 2
  const mm = (index * 7) % 60
  return {
    id: 1000 + index,
    username: logUsers[index % logUsers.length],
    module: logModules[index % logModules.length],
    action: logActions[index % logActions.length],
    method: logMethods[index % logMethods.length],
    ip: logIps[index % logIps.length],
    status: index % 9 === 4 ? 0 : 1,
    costMs: 30 + ((index * 17) % 260),
    createTime: `2025-11-${pad(26 - dayOffset)} ${pad(hour)}:${pad(mm)}:${pad((index * 11) % 60)}`,
    params: JSON.stringify({ id: index + 1, pageSize: index % 2 === 0 ? 10 : 20 }),
  }
})

